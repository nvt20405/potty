		public static ushort Crc16(byte[] data, int offset, uint length)
		{
			ushort num = 0;
			while (length != 0)
			{
				num = UPDC16(data[offset], num);
				offset++;
				length--;
			}
			return num;
		}

		public static ushort CrcCcitt(byte[] data, int offset, uint length)
		{
			ushort num = 0;
			while (length != 0)
			{
				num = UPDCCCITT(data[offset], num);
				offset++;
				length--;
			}
			return num;
		}

		public static uint Crc32(byte[] data, int offset, uint length)
		{
			uint num = uint.MaxValue;
			while (length != 0)
			{
				num = UPDC32(data[offset], num);
				offset++;
				length--;
			}
			return ~num;
		}

		private static ushort UPDC16(byte cp, ushort crc)
		{
			return (ushort)(Crc16Table[(crc ^ cp) & 0xFF] ^ (crc >> 8));
		}

		private static ushort UPDCCCITT(byte cp, ushort crc)
		{
			return (ushort)(CrcCcittTable[(crc >> 8) & 0xFF] ^ (crc << 8) ^ cp);
		}

		private static uint UPDC32(byte octet, uint crc)
		{
			return Crc32Table[(uint)(UIntPtr)((crc ^ octet) & 0xFF)] ^ (crc >> 8);
		}
